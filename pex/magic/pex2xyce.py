#!/usr/bin/env python3
"""Make the magic PEX netlist usable in place of SARADC.xyce.ckt: rename the extracted cell to
SARADC_PEX, wrap it in a SARADC subcircuit with the port order of the schematic netlist, and
replace '#' in node names (magic's names for unlabeled nets).

  pex2xyce.py SARADC.pex.spice schematic.ckt out.ckt
"""
import re
import sys

pex, sch, out = sys.argv[1:4]

def ports(path, name):
    txt = open(path).read()
    m = re.search(r"^\.subckt\s+%s\s+(.*?)\n(?!\+)" % name, txt, re.I | re.M | re.S)
    return m.group(1).replace("\n+", " ").split()

sch_ports = ports(sch, "SARADC")
pex_ports = ports(pex, "SARADC")
assert sorted(sch_ports) == sorted(pex_ports), (sch_ports, pex_ports)

with open(pex) as fi, open(out, "w") as fo:
    fo.write("* SARADC post-layout netlist (magic extraction with parasitic C), generated by pex2xyce.py\n")
    for line in fi:
        if re.match(r"^\.subckt\s+SARADC\s", line, re.I):
            line = re.sub(r"^\.subckt\s+SARADC", ".subckt SARADC_PEX", line, flags=re.I)
        fo.write(line.replace("#", "_h"))
    fo.write("\n.subckt SARADC %s\n" % " ".join(sch_ports))
    fo.write("Xpex %s SARADC_PEX\n.ends\n" % " ".join(pex_ports))
print("ports:", " ".join(sch_ports))
