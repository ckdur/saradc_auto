SUPPLY = 1.8
VREFH = SUPPLY * 0.9 / 1.2
VREFL = SUPPLY * 0.3 / 1.2
VCM = SUPPLY / 2
VFS = 2 * (VREFH - VREFL)  # Differential full scale (peak-to-peak)
LSB = VFS / NCODES


def set_conditions(vdd, vrefh, vrefl, vcm):
    """Supply, references and input common mode (default: those of saradc_tb_body.sp)."""
    global SUPPLY, VREFH, VREFL, VCM, VFS, LSB
    SUPPLY = vdd
    VREFH = vrefh if vrefh is not None else vdd * 0.9 / 1.2
    VREFL = vrefl if vrefl is not None else vdd * 0.3 / 1.2
    VCM = vcm if vcm is not None else vdd / 2
    VFS = 2 * (VREFH - VREFL)
    LSB = VFS / NCODES

