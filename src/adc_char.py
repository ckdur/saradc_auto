#!/usr/bin/env python3
"""Transistor-level characterization of the SARADC with ngspice (default) or Xyce, under the
conditions of the bench measurement (clock fclk, one conversion every 7 clocks).

The record is split into many short, independent simulator jobs that run in parallel, one process
each. A job simulates a warm-up conversion and then K conversions; the input of each job is
either a DC staircase (one level per conversion) or a slice of a coherent sine (the source phase
is shifted so the job samples the right part of the record).

  adc_char.py bench  [--k K]                         time one job
  adc_char.py static [--step-lsb S] [--refine R]     transition levels: coarse staircase + bisection
  adc_char.py sine   --freq F [--n N]                coherent sine record of N samples
  adc_char.py all                                    static + the sine sweep

Results go to sim/outputs/char/<netlist>/ (see --netlist). Use the environment of init_openlane.sh.
"""
