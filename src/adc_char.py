MOS_MODELS = ("sg13_lv_nmos", "sg13_lv_pmos", "sg13_hv_nmos", "sg13_hv_pmos")


GEOM = ("as", "ad", "ps", "pd")  # Junction area/perimeter: linear in the junction charges


def spice_num(v):
    sc = {"t": 1e12, "g": 1e9, "meg": 1e6, "k": 1e3, "m": 1e-3, "u": 1e-6, "n": 1e-9, "p": 1e-12, "f": 1e-15}
    m = re.match(r"^([-+0-9.eE]+)(meg|[tgkmunpf])?", v.lower())
    return float(m.group(1)) * sc.get(m.group(2) or "", 1.0)


def merge_parallel(src, dst):
    """Copy a netlist, merging MOS instances that are exactly in parallel (same nodes, model, W, L;
    drain/source may be swapped) into one instance with the summed multiplier. Junction areas and
    perimeters may differ between fingers (edge fingers of an extracted layout): the merged
    instance gets their m-weighted average, which keeps the total junction charge."""
    lines = []
    with open(src) as f:
        for line in f:
            if line.startswith("+") and lines:
                lines[-1] = lines[-1].rstrip("\n") + " " + line[1:]
            else:
                lines.append(line)
    out, groups, ndev = [], {}, 0

    def flush():
        for i, mm, head, rest, geo in groups.values():
            g = ["%s=%.6g" % (k, geo[k] / mm) for k in GEOM if k in geo]
            out[i] = " ".join(head + rest + g + ["m=%g" % mm]) + "\n"
        groups.clear()

    for line in lines:
        tok = line.split()
        if tok and tok[0][0] in "Xx" and len(tok) > 5 and tok[5].lower() in MOS_MODELS:
            ndev += 1
            d, g, s, b = tok[1:5]
            m, rest, geo = 1.0, [], {}
            for t in tok[6:]:
                k = t.split("=")[0].lower()
                if t.startswith("$"):
                    continue
                if k == "m":
                    m = spice_num(t[2:])
                elif k in GEOM:
                    geo[k] = spice_num(t.split("=")[1])
                else:
                    rest.append(t)
            key = (tuple(sorted((d, s))), g, b, tok[5].lower(), tuple(rest))
            if key not in groups:
                groups[key] = [len(out), 0.0, tok[:6], rest, {}]
                out.append(None)
            grp = groups[key]
            grp[1] += m
            for k, v in geo.items():
                grp[4][k] = grp[4].get(k, 0.0) + m * v
        else:
            if tok and tok[0].lower() == ".ends":  # Groups never cross a subcircuit
                flush()
            out.append(line)
    flush()
    # Atomic: another run may be reading dst
    with open(dst + ".tmp%d" % os.getpid(), "w") as f:
        f.writelines(out)
    os.replace(f.name, dst)
    return ndev, sum(1 for l in out if l.split() and l.split()[0][0] in "Xx"
                     and len(l.split()) > 5 and l.split()[5].lower() in MOS_MODELS)


def flatten(files, top, dst):
    """Flatten the subcircuit top (with every subcircuit it uses, from files) down to the MOS
    instances, keeping the ports of top. Lets merge_parallel see the parallel switches too."""
    subs, cur = {}, None
    for fn in files:
        lines = []
        with open(fn) as f:
            for line in f:
                if line.startswith("+") and lines:
                    lines[-1] = lines[-1].rstrip("\n") + " " + line[1:]
                else:
                    lines.append(line)
        for line in lines:
            tok = line.split()
            if not tok or tok[0].startswith("*"):
                continue
            k = tok[0].lower()
            if k == ".subckt":
                cur = tok[1]
                subs[cur.lower()] = (tok[2:], [])
            elif k == ".ends":
                cur = None
            elif cur is not None:
                subs[cur.lower()][1].append(tok)
    out = []

    def expand(name, nodes, prefix):
        pins, body = subs[name.lower()]
        nmap = dict(zip(pins, nodes))
        nm = lambda n: nmap.get(n, n if n.lower() in ("0", "gnd") else prefix + n)
        for tok in body:
            if tok[0][0] in "Xx":
                args = [t for t in tok[1:] if "=" not in t and not t.startswith("$")]
                model = args[-1]
                if model.lower() in subs:
                    expand(model, [nm(n) for n in args[:-1]], prefix + tok[0] + ".")
                    continue
                if model.lower() in MOS_MODELS:
                    par = [t for t in tok[1:] if "=" in t and not t.startswith("$")]
                    out.append(" ".join([tok[0][0] + prefix.replace(".", "_") + tok[0][1:]] +
                                        [nm(n) for n in args[:-1]] + [model] + par))
                    continue
                raise ValueError("unknown subcircuit " + model)
            raise ValueError("unsupported element " + " ".join(tok))

    pins = subs[top.lower()][0]
    expand(top, pins, "")
    with open(dst, "w") as f:
        f.write("* %s flattened by adc_char.py\n.subckt %s %s\n" % (top, top, " ".join(pins)))
        f.write("\n".join(out) + "\n.ends\n")
    return len(out)


def ng2csv(dat, csv):
    """wrdata (single scale, vector names) to the column names of the Xyce CSV."""
    with open(dat) as f:
        names = f.readline().split()
    d = np.loadtxt(dat, skiprows=1)
    names = ["TIME"] + ["V" + n[2:-1].upper() for n in names[1:]]
    np.savetxt(csv, d, delimiter=",", header=",".join(names), comments="", fmt="%.9e")
    os.remove(dat)


def body():
    """saradc_tb_body.sp without its input sources and analysis, and without the result capture
    registers and the ideal reconstruction DAC: they only observe RESULT (read here directly at
    VALID), and their flip-flop/mux node validn makes the ngspice timestep collapse. Each RESULT
    line keeps a load of Cdigload plus the mux input it drove."""
    out = []
    with open(os.path.join(SRC, "saradc_tb_body.sp")) as f:
        for line in f:
            l = line.strip().lower()
            if l.startswith(("vvinr", "vvipr", "vvindc", ".tran", "xneg0", "xcap", "xi1 ", "cr",
                             ".include dac_r2r_ideal.sp", ".ic v(resultq", ".ic v(validn")):
                continue
            if l.startswith(".param supply="):
                line = ".PARAM supply=%g\n" % SUPPLY
            elif l.startswith(".param vrefhval="):
                line = ".PARAM vrefhval=%g\n" % VREFH
            elif l.startswith(".param vreflval="):
                line = ".PARAM vreflval=%g\n" % VREFL
            out.append(line)
    out += ["cres%d result_%d gnd {Cdigload+2e-15}\n" % (i, i) for i in range(NBITS)]
    return "".join(out)


def pdk_version(pdk):
    """Git state of the PDK checkout, recorded with the results (the checkout may move later)."""
    git = lambda *a: subprocess.run(["git", "-C", pdk] + list(a), capture_output=True, text=True).stdout.strip()
    commit = git("log", "-1", "--format=%h")
    if not commit:
        return None
    return {"name": os.path.basename(pdk), "commit": commit, "describe": git("describe", "--tags", "--always"),
            "branch": git("rev-parse", "--abbrev-ref", "HEAD"), "date": git("log", "-1", "--format=%cd", "--date=short"),
            "remote": git("remote", "get-url", "origin")}


class Bench:
    def __init__(self, fclk, netlist, corner, temp, outdir, trtol=1, merge=True, sim="xyce"):
        self.fclk = fclk
        self.tclk = 1 / fclk
        self.ts = CLK_PER_CONV * self.tclk
        self.netlist = netlist
        self.corner = corner
        self.temp = temp
        self.outdir = outdir
        self.pdk = os.path.join(os.environ["PDK_ROOT"], os.environ["PDK"])
        self.body = body()
        self.trtol = trtol
        self.sim = sim
        os.makedirs(outdir, exist_ok=True)
        with open(os.path.join(outdir, "pdk.json"), "w") as f:
            json.dump(pdk_version(self.pdk), f, indent=1)
        self.capcell = os.path.join(SIMOUT if sim == "xyce" else CELLS, "SARADC_CELL_INVX16_ASCAP.ckt")
        if merge:
            # The unit capacitors are 12+12 fingers in parallel: one instance each is exact
            # and makes the circuit about three times smaller
            cc = os.path.join(outdir, "SARADC_CELL_INVX16_ASCAP.merged.ckt")
            print("cap cell: %d -> %d MOS" % merge_parallel(self.capcell, cc))
            self.capcell = cc
            nl = os.path.join(outdir, os.path.basename(netlist) + ".merged")
            print("netlist: %d -> %d MOS" % merge_parallel(netlist, nl))
            self.netlist = nl

    def sample_window(self, j):
        """Local conversion j (0 = warm-up): SAMPLE is high during [t0, t0 + tclk]."""
        t0 = (FIRST_SAMPLE_CLK + CLK_PER_CONV * j) * self.tclk
        return t0, t0 + self.tclk

    def tstop(self, nconv):
        return (FIRST_SAMPLE_CLK + CLK_PER_CONV * nconv + 1) * self.tclk

    def write(self, name, sources, nconv):
        path = os.path.join(self.outdir, name + ".sp")
        csv = os.path.join(self.outdir, name + ".csv")
        old = open(path).read() if os.path.exists(path) else None
        with open(path, "w") as f:
            if self.sim == "xyce":
                f.write(HEADER.format(temp=self.temp, pdk=self.pdk, corner=self.corner, simout=SIMOUT,
                                      netlist=self.netlist, fclk=self.fclk, trtol=self.trtol,
                                      capcell=self.capcell))
                f.write(self.body)
                f.write(FOOTER.format(sources=sources, csv=csv, tstop="%.6e" % self.tstop(nconv)))
            else:
                f.write(HEADER_NG.format(temp=self.temp, pdk=self.pdk, corner=self.corner, cells=CELLS,
                                         netlist=self.netlist, fclk=self.fclk, trtol=self.trtol,
                                         capcell=self.capcell))
                f.write(self.body)
                f.write(FOOTER_NG.format(sources=sources, raw=csv[:-4] + ".dat",
                                         tstop="%.6e" % self.tstop(nconv)))
        # A cached result is only reused for the same job
        if old != open(path).read() and os.path.exists(csv):
            os.remove(csv)
        return path, csv

    def staircase_job(self, name, levels):
        """One conversion per differential level; a warm-up conversion at the first level."""
        levels = [levels[0]] + list(levels)
        pts_p, pts_n = [], []
        for j, vd in enumerate(levels):
            # Change the level in the middle of the previous conversion (input switches open)
            tc = self.sample_window(j)[0] - 3.5 * self.tclk if j else 0.0
            for (t, v) in ((tc, vd),) if j == 0 else ((tc, levels[j - 1]), (tc + 1e-9, vd)):
                pts_p.append((t, VCM + v / 2))
                pts_n.append((t, VCM - v / 2))
        fmt = lambda pts: " ".join("%.6e %.6f" % p for p in pts)
        src = "vvipr vipr gnd PWL {}\nvvinr vinr gnd PWL {}\n".format(fmt(pts_p), fmt(pts_n))
        return self.write(name, src, len(levels))

    def sine_job(self, name, freq, amp, k0, k, gbw=None):
        """Conversions k0..k0+k-1 of a sine sampled every ts (plus a warm-up conversion).
        With gbw, the two inputs go through the linear model of the board front end."""
        # Local conversion j=1 must see the phase of global sample k0
        ph = (360.0 * freq * ((k0 - 1) * self.ts)) % 360.0
        # amp is the differential peak-to-peak: each side swings a quarter of it
        hp, hn = frontend(freq, gbw) if gbw else (1.0, -1.0)
        src = ("vvipr vipr gnd SIN {vcm} {ap} {f} 0 0 {php}\n"
               "vvinr vinr gnd SIN {vcm} {an} {f} 0 0 {phn}\n").format(
            vcm=VCM, f=freq, ap=amp / 4 * abs(hp), an=amp / 4 * abs(hn),
            php=(ph + np.degrees(np.angle(hp))) % 360.0, phn=(ph + np.degrees(np.angle(hn))) % 360.0)
        return self.write(name, src, k + 1)

    def run(self, path, csv, force=False):
        log = path[:-3] + ".log"
        if os.path.exists(csv) and not force:
            return csv
        if self.sim == "xyce":
            cmd = [c.format(self.pdk) for c in XYCE] + [path]
        else:
            # The PDK .spiceinit loads the OSDI models; ngspice reads it from the working directory
            init = os.path.join(self.outdir, ".spiceinit")
            if not os.path.exists(init):
                with open(os.path.join(self.pdk, "libs.tech", "ngspice", ".spiceinit")) as fi, open(init, "w") as fo:
                    fo.write(fi.read() + "\nset num_threads=1\n")
            cmd = ["ngspice", "-b", path]
        t = time.time()
        for attempt in range(2):
            with open(log, "w") as f:
                r = subprocess.run(cmd, cwd=self.outdir, stdout=f, stderr=subprocess.STDOUT, env=ENV)
            if self.sim != "ngspice" or r.returncode != 0:
                break
            # ngspice exits with 0 even when the transient aborts ("Timestep too small" at the
            # digital edges): retry once with a tighter reltol
            with open(log, errors="replace") as f:
                if "aborted" not in f.read():
                    ng2csv(csv[:-4] + ".dat", csv)
                    break
            if attempt:
                raise RuntimeError("ngspice aborted: " + log)
            with open(path) as f:
                net = f.read().replace("reltol=1e-4", "reltol=1e-5")
            with open(path, "w") as f:
                f.write(net)
        if r.returncode != 0 or not os.path.exists(csv):
            raise RuntimeError("%s failed: %s" % (self.sim, log))
        with open(log, "a") as f:
            f.write("\nWALL %.1f\n" % (time.time() - t))
        return csv

    def decode(self, csv):
        """Codes of every conversion (local order), with the sampled differential input."""
        d = np.genfromtxt(csv, delimiter=",", names=True)
        t = d["TIME"]
        valid = d["VVALID"] > SUPPLY / 2
        rises = np.where(~valid[:-1] & valid[1:])[0]
        falls = np.where(valid[:-1] & ~valid[1:])[0]
        codes = []
        # VALID can glitch high during the reset: only pulses after the first sample count
        rises = rises[t[rises] > (FIRST_SAMPLE_CLK + 1) * self.tclk]
        for r in rises:
            f = falls[falls > r]
            if not len(f):
                continue
            i = (r + f[0]) // 2
            codes.append(sum(int(d["VRESULT_%d" % b][i] > SUPPLY / 2) << b for b in range(NBITS)))
        # Input at the end of each sampling window
        vd = d["VVIP"] - d["VVIN"]
        vs = [np.interp(self.sample_window(j)[1], t, vd) for j in range(len(codes))]
        return np.array(codes), np.array(vs)


def parallel(bench, jobs, workers):
    """jobs: list of (path, csv). Runs them and returns the decoded results in order."""
    errors = []
    with cf.ThreadPoolExecutor(max_workers=workers) as ex:
        futs = [ex.submit(bench.run, p, c) for p, c in jobs]
        for i, fu in enumerate(cf.as_completed(futs)):
            try:
                fu.result()
            except RuntimeError as e:  # Let the other jobs finish, their CSV are kept
                errors.append(str(e))
            print("  %d/%d jobs done%s" % (i + 1, len(jobs), " (%d failed)" % len(errors) if errors else ""),
                  flush=True)
    if errors:
        raise RuntimeError("\n".join(errors))
    return [bench.decode(c) for _, c in jobs]


def cmd_bench(b, a):
    levels = np.linspace(-0.8, 0.8, a.k)
    p, c = b.staircase_job("bench_k%d_tr%g" % (a.k, b.trtol), levels)
    t = time.time()
    b.run(p, c, force=True)
    codes, vs = b.decode(c)
    dt = time.time() - t
    print("Job of %d conversions (+1 warm-up): %.1f s, %.1f s/conversion" % (a.k, dt, dt / (a.k + 1)))
    for v, cd in zip(vs, codes):
        print("  vd %+.4f V -> %2d (ideal %2d)" % (v, cd, int(np.clip(np.floor(v / LSB) + NCODES / 2, 0, NCODES - 1))))


def run_levels(b, a, tag, levels):
    """Convert every level (in parallel jobs of a.k conversions); returns codes in order."""
    jobs = []
    for i in range(0, len(levels), a.k):
        jobs.append(b.staircase_job("%s_%03d" % (tag, i // a.k), levels[i:i + a.k]))
    res = parallel(b, jobs, a.workers)
    return np.concatenate([c[1:] for c, _ in res])  # Drop the warm-up conversions


def cmd_static(b, a):
    """Coarse staircase, then bisection of every transition."""
    lo, hi = -VFS / 2 - LSB, VFS / 2 + LSB
    coarse = np.arange(lo, hi + 1e-9, a.step_lsb * LSB)
    codes = run_levels(b, a, "static_coarse", coarse)
    # With a gain error the ends of the staircase may not reach codes 0 and NCODES-1:
    # extend it by one job of a.k levels at a time on that side
    step = a.step_lsb * LSB
    for i in range(8):
        if codes[0] > 0:
            ext = coarse[0] - step * np.arange(a.k, 0, -1)
            coarse, codes = np.concatenate([ext, coarse]), np.concatenate([run_levels(b, a, "static_lo%d" % i, ext), codes])
        if codes[-1] < NCODES - 1:
            ext = coarse[-1] + step * np.arange(1, a.k + 1)
            coarse, codes = np.concatenate([coarse, ext]), np.concatenate([codes, run_levels(b, a, "static_hi%d" % i, ext)])
        if codes[0] == 0 and codes[-1] == NCODES - 1:
            break
    # Bracket every transition k (code >= k) between two coarse points
    br = {}
    for k in range(1, NCODES):
        above = np.where(codes >= k)[0]
        if not len(above) or above[0] == 0:
            continue
        br[k] = [coarse[above[0] - 1], coarse[above[0]]]
    # The transitions found in the extensions go last, so the jobs of the other ones stay the
    # same as without extension (and their cached results stay valid)
    lo, hi = -VFS / 2 - LSB - 1e-9, VFS / 2 + LSB + 1e-9
    ks = sorted(br, key=lambda k: (not (lo <= br[k][0] and br[k][1] <= hi), k))
    for r in range(a.refine):
        mids = np.array([(br[k][0] + br[k][1]) / 2 for k in ks])
        c = run_levels(b, a, "static_refine%d" % r, mids)
        for k, m, cd in zip(ks, mids, c):
            if cd >= k:
                br[k][1] = m
            else:
                br[k][0] = m
        print("refine %d: bracket %.2f mV" % (r, (br[ks[0]][1] - br[ks[0]][0]) * 1e3), flush=True)
    t = {k: (v[0] + v[1]) / 2 for k, v in br.items()}
    res = {"fclk": b.fclk, **conditions(), "lsb_ideal": LSB, "vfs": VFS, "coarse_levels": coarse.tolist(),
           "coarse_codes": codes.tolist(), "transitions": {str(k): t[k] for k in sorted(t)},
           "resolution": max(v[1] - v[0] for v in br.values())}
    with open(os.path.join(b.outdir, "static.json"), "w") as f:
        json.dump(res, f, indent=1)
    print("Saved", os.path.join(b.outdir, "static.json"))


def frontend(freq, gbw, r=47.5, cd=1.2e-9, cg=120e-12):
    """Complex gains to VIP and VIN of the single-ended to differential stage of the adapter
    board: a unity buffer (VIP), an inverter with two 1k after it (VIN), single-pole op-amps of
    gain-bandwidth gbw, then 47.5 ohm per side, cd across the pair and cg from each side to ground."""
    s = 2j * np.pi * freq
    hb = 1 / (1 + s / (2 * np.pi * gbw))
    hi = -1 / (1 + 2 * s / (2 * np.pi * gbw))  # noise gain 2
    d = (hb - hb * hi) / 2 / (1 + s * r * (2 * cd + cg))
    c = (hb + hb * hi) / 2 / (1 + s * r * cg)
    return c + d, c - d


def conditions():
    return {"vdd": SUPPLY, "vrefh": VREFH, "vrefl": VREFL, "vcm": VCM}


def odd_prime_cycles(freq, fs, n):
    k = max(3, int(round(freq * n / fs)))
    isprime = lambda m: m > 2 and m % 2 and all(m % d for d in range(3, int(m ** 0.5) + 1, 2))
    for d in range(n):
        for c in (k - d, k + d):
            if isprime(c):
                return c


def cmd_sine(b, a):
    """All the frequencies go through one pool of jobs, then each record is saved."""
    fs = 1 / b.ts
    recs, jobs = [], []
    for freq in a.freq:
        j = odd_prime_cycles(freq, fs, a.n)
        f = j * fs / a.n
        amp = a.amp_lsb * LSB
        tag = ("sinefe_%dk" if a.frontend else "sine_%dk") % round(f / 1e3)
        js = [b.sine_job("%s_%03d" % (tag, i // a.k), f, amp, i, min(a.k, a.n - i), a.frontend)
              for i in range(0, a.n, a.k)]
        print("%s: %.3f Hz, %d cycles in %d samples, %d jobs" % (tag, f, j, a.n, len(js)), flush=True)
        recs.append((tag, f, j, amp, len(jobs), len(js)))
        jobs += js
    res = parallel(b, jobs, a.workers)
    for tag, f, j, amp, i0, nj in recs:
        r = res[i0:i0 + nj]
        codes = np.concatenate([c[1:] for c, _ in r])
        vs = np.concatenate([v[1:] for _, v in r])
        out = {"fclk": b.fclk, **conditions(), "frontend_gbw": a.frontend, "fs": fs, "freq": f, "cycles": j, "n": a.n, "amp_vpp": amp,
               "codes": codes.tolist(), "vin_sampled": vs.tolist()}
        with open(os.path.join(b.outdir, tag + ".json"), "w") as fo:
            json.dump(out, fo)
        print("Saved", os.path.join(b.outdir, tag + ".json"), flush=True)


